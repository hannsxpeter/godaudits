function sourceProof(repo, relative, level = 2) {
  const value = fs.readFileSync(path.join(repo, relative), 'utf8');
  return {
    level,
    kind: level === 3 ? 'failure-path' : 'citation',
    path: relative,
    line: 1,
    quote: value.trim(),
    sha256: crypto.createHash('sha256').update(value).digest('hex'),
    ...(level === 3 ? { steps: ['Call enters cacheKey.', 'The tenant guard rejects a mismatched tenant.'] } : {})
  };
}

function executableProof(command, result = 'passed') {
  return {
    level: 4,
    kind: 'executable',
    tool: 'node:test',
    tool_version: process.versions.node,
    command,
    result,
    environment: 'disposable local fixture',
    isolation: 'outbound network disabled and no production credentials'
  };
}

function resultsFor(review, values = {}) {
  return {
    schema_version: '1.0',
    review: {
      base: review.review.base,
      head: review.review.head,
      diff_sha256: review.review.diff_sha256
    },
    ...values
  };
}

