test('applyBlastRadiusResults records proof, real risks, cleared risks, and a passing merge gate', (t) => {
  const { repo, base, head } = fixture(t);
  const review = planBlastRadius(repo, {
    base,
    head,
    facts: [
      'Cache keys remain tenant-scoped after the cache helper signature changes.',
      'The item API remains backward-compatible for existing consumers.'
    ],
    verify: 'node --test test/cache-contract.test.js'
  });
  const results = resultsFor(review, {
    authorization: {
      capability: 'sandbox',
      authorized_by: 'repository owner',
      environment: 'disposable local fixture',
      isolation: 'outbound network disabled and no production credentials'
    },
    safety_facts: [
      { fact: 'SF-1', outcome: 'proven', proof: executableProof('node --test test/cache-key.test.js') },
      { fact: 'SF-2', outcome: 'proven', proof: executableProof('node --test test/api-contract.test.js') }
    ],
    risks: [{
      title: 'Legacy cache entries can miss after deployment',
      mechanism: 'Old and new processes compute different cache keys during a rolling deployment.',
      likelihood: 'unlikely',
      consequence: 'Low',
      verify: 'node --test test/cache-rollout.test.js',
      proof: sourceProof(repo, 'src/cache.js')
    }],
    cleared: [{
      title: 'The API response shape remains readable by old clients',
      rationale: 'The response schema only gains optional metadata.',
      invalidated_by: 'Making the metadata field required or removing an existing response field.',
      proof: sourceProof(repo, 'api/openapi.json', 3)
    }],
    before_merge: {
      outcome: 'passed',
      proof: executableProof('node --test test/cache-contract.test.js')
    }
  });

  const applied = applyBlastRadiusResults(review, results);
  assert.deepEqual(applied.errors, []);
  assert.equal(applied.review.merge_gate.status, 'pass');
  assert.equal(applied.review.safety_facts[0].proof_level, 4);
  assert.equal(applied.review.safety_facts[0].status, 'proven');
  assert.equal(applied.review.risks[0].likelihood, 'unlikely');
  assert.equal(applied.review.cleared[0].proof_level, 3);
  assert.equal(applied.review.before_merge.status, 'passed');
  assert.ok(applied.review.review.capabilities.includes('sandbox'));
  const evidence = exportChangeReviewEvidence(applied.review, { start: 40, source: 'CHANGE-REVIEW.json' });
  assert.equal(evidence.evidence[0].id, 'E-40');
  assert.ok(evidence.evidence.some((item) => item.type === 'source'));
  assert.ok(evidence.evidence.some((item) => item.type === 'runtime'));
  assert.equal(evidence.findings_created, 0);
  assert.match(renderBlastRadius(applied.review), /Merge disposition: PASS/);
  assert.match(renderBlastRadius(applied.review), /Cleared risks/);
});

