test('an open high-consequence risk blocks a fully proven change', (t) => {
  const { repo, base, head } = fixture(t);
  const review = planBlastRadius(repo, {
    base,
    head,
    facts: ['Cache keys remain tenant-scoped after the cache helper signature changes.'],
    verify: 'node --test test/cache-contract.test.js'
  });
  const proof = executableProof('node --test test/cache-key.test.js');
  const applied = applyBlastRadiusResults(review, resultsFor(review, {
    authorization: {
      capability: 'sandbox',
      authorized_by: 'repository owner',
      environment: 'disposable local fixture',
      isolation: 'outbound network disabled and no production credentials'
    },
    safety_facts: [{ fact: 'SF-1', outcome: 'proven', proof }],
    risks: [{
      title: 'Tenant cache entries collide',
      mechanism: 'The new key omits the tenant identifier.',
      likelihood: 'likely',
      consequence: 'High',
      verify: 'node --test test/cache-key.test.js',
      proof: sourceProof(repo, 'src/cache.js')
    }],
    before_merge: { outcome: 'passed', proof: executableProof('node --test test/cache-contract.test.js') }
  }));
  assert.deepEqual(applied.errors, []);
  assert.equal(applied.review.merge_gate.status, 'blocked');
  assert.ok(applied.review.merge_gate.reasons.some((reason) => /High/.test(reason)));
});

