test('planning and applying proof never execute recorded commands and redact credentials', (t) => {
  const { repo, base, head } = fixture(t);
  const marker = path.join(repo, 'must-not-exist');
  const fakeToken = ['ghp', 'abcdefghijklmnopqrstuvwxyz123456'].join('_');
  const command = `${process.execPath} -e "require('fs').writeFileSync('${marker}','ran')" token=${fakeToken}`;
  const review = planBlastRadius(repo, {
    base,
    head,
    facts: ['Cache keys remain tenant-scoped after the cache helper signature changes.'],
    verify: command
  });
  assert.equal(fs.existsSync(marker), false);
  assert.equal(JSON.stringify(review).includes(fakeToken), false);
  const applied = applyBlastRadiusResults(review, resultsFor(review, {
    authorization: {
      capability: 'sandbox',
      authorized_by: 'repository owner',
      environment: 'disposable local fixture',
      isolation: 'outbound network disabled and no production credentials'
    },
    before_merge: {
      outcome: 'passed',
      proof: executableProof(review.before_merge.command, `passed with token ${fakeToken}`)
    }
  }));
  assert.equal(fs.existsSync(marker), false);
  assert.equal(JSON.stringify(applied.review).includes(fakeToken), false);
});

