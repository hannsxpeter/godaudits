test('semantic validation rejects a hand-authored pass that launders lower-level proof', (t) => {
  const { repo, base, head } = fixture(t);
  const review = planBlastRadius(repo, {
    base,
    head,
    facts: ['Cache keys remain tenant-scoped after the cache helper signature changes.'],
    verify: 'node --test test/cache-contract.test.js'
  });
  const applied = applyBlastRadiusResults(review, resultsFor(review, {
    safety_facts: [{ fact: 'SF-1', outcome: 'proven', proof: sourceProof(repo, 'src/cache.js', 3) }]
  }));
  assert.deepEqual(applied.errors, []);
  const forged = applied.review;
  forged.safety_facts[0].proof_level = 4;
  forged.safety_facts[0].proof_kind = 'executable';
  forged.safety_facts[0].stopped_because = null;
  forged.before_merge.status = 'passed';
  forged.before_merge.proof_ids = [...forged.safety_facts[0].proof_ids];
  forged.merge_gate = { status: 'pass', reasons: [] };
  const errors = validateChangeReview(forged);
  assert.ok(errors.some((error) => /must match its current proof/.test(error)));
  assert.ok(errors.some((error) => /before_merge passed requires level 4 or 5 proof/.test(error)));
  assert.ok(errors.some((error) => /merge_gate/.test(error)));
});

